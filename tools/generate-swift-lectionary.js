// Generates MtcCounter/Models/LectionaryData.swift from src/lectionary.js so
// the iOS app uses exactly the same lectionary as the web app.
//
//   node tools/generate-swift-lectionary.js
//
// tests/swift-sync.test.js fails if the committed Swift file is out of date.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const SWIFT_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'MtcCounter', 'Models', 'LectionaryData.swift');

const swiftString = v => '"' + String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const opt = v => (v === undefined || v === null || v === '' ? 'nil' : swiftString(v));

export function renderSwiftLectionary(lectionary) {
  const lines = Object.keys(lectionary).sort().map(date => {
    const e = lectionary[date];
    return '        ' + swiftString(date) + ': LectionaryEntry(occasion: ' + opt(e.occasion)
      + ', theme: ' + opt(e.theme) + ', gospel: ' + opt(e.gospel) + '),';
  });
  return [
    '// GENERATED by tools/generate-swift-lectionary.js from src/lectionary.js.',
    '// Do not edit by hand: change src/lectionary.js and re-run the generator.',
    '',
    'import Foundation',
    '',
    'enum LectionaryData {',
    '    static let entries: [String: LectionaryEntry] = [',
    ...lines,
    '    ]',
    '}',
    '',
  ].join('\n');
}

// Run directly: write the file.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!globalThis.localStorage) {
    const m = new Map();
    globalThis.localStorage = { getItem: k => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: k => m.delete(k) };
  }
  const { LECTIONARY } = await import('../src/lectionary.js');
  writeFileSync(SWIFT_PATH, renderSwiftLectionary(LECTIONARY));
  console.log('Wrote', SWIFT_PATH, '(' + Object.keys(LECTIONARY).length + ' entries)');
}
