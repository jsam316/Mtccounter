// Generates MtcCounter/Models/OffertoryData.swift from src/offertory.js so
// the iPhone app counts the offertory with exactly the same currencies,
// notes and coins as the web app.
//
//   node tools/generate-swift-offertory.js
//
// tests/swift-sync.test.js fails if the committed Swift file is out of date.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

export const SWIFT_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'MtcCounter', 'Models', 'OffertoryData.swift');

const str = v => '"' + String(v).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

export function renderSwiftOffertory(table) {
  const lines = table.map(c =>
    '        OffertoryCurrency(code: ' + str(c.code) + ', name: ' + str(c.name) + ', plural: ' + str(c.plural)
    + ', minorName: ' + str(c.minor) + ', decimals: ' + c.decimals + ',\n'
    + '                          denominations: [' + c.denominations.map(str).join(', ') + ']),');
  return [
    '// GENERATED by tools/generate-swift-offertory.js from src/offertory.js.',
    '// Do not edit by hand: change src/offertory.js and re-run the generator.',
    '',
    'import Foundation',
    '',
    'enum OffertoryData {',
    '    /// Every currency the offertory can be counted in. `denominations` are',
    '    /// its notes and coins as printed, largest first.',
    '    static let currencies: [OffertoryCurrency] = [',
    ...lines,
    '    ]',
    '}',
    '',
  ].join('\n');
}

// Run directly: write the file.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!globalThis.localStorage) {
    const m = new Map();
    globalThis.localStorage = { getItem: k => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: k => m.delete(k) };
  }
  const { currencyTable } = await import('../src/offertory.js');
  writeFileSync(SWIFT_PATH, renderSwiftOffertory(currencyTable()));
  console.log('Wrote', SWIFT_PATH, '(' + currencyTable().length + ' currencies)');
}
